import { Link, useParams } from "react-router-dom";
import { ArrowLeft, Printer } from "lucide-react";
import { api, fmtDate, fmtDateTime, inr, offenderLabel, VEHICLE_LABEL } from "../api";
import { BrandMark } from "../components/Layout";
import { Empty, useApp, usePolling } from "../components/ui";

// Printable notice. Wording is generic on purpose: the legal basis (SWM Rules 2016 +
// the city's own bye-laws) and amounts differ between urban local bodies.
export default function Notice() {
  const { id } = useParams();
  const { settings } = useApp();
  const res = usePolling(() => api.incident(id!), [id], 0);
  const d = res.data;
  if (res.error && !d) return <Empty title="Notice not found">{res.error}</Empty>;
  if (!d) return <div className="muted">Loading…</div>;
  if (!d.notice_number) return <Empty title="No notice issued yet">Verify the case and issue a notice first.</Empty>;

  const vehicle = d.offender_type === "vehicle";
  return (
    <>
      <Link to={`/incidents/${d.id}`} className="back"><ArrowLeft size={16} /> Back to case #{d.id}</Link>
      <div className="notice-actions">
        <button className="btn primary" onClick={() => window.print()}><Printer /> Print / save as PDF</button>
      </div>
      <article className="notice-page">
        <div className="n-head">
          <div>
            <h1>{settings?.municipality || "Municipal Corporation"}</h1>
            <div>{settings?.department || "Solid Waste Management Department"}</div>
            <div style={{ fontSize: 12, color: "#555" }}>{d.ward || ""}{d.location ? ` · ${d.location}` : ""}</div>
          </div>
          <div style={{ textAlign: "right", fontSize: 13 }}>
            <div style={{ display: "flex", justifyContent: "flex-end", marginBottom: 6 }}><BrandMark /></div>
            <div><b>Notice No:</b> {d.notice_number}</div>
            <div><b>Date:</b> {fmtDate(d.notice_issued_at)}</div>
          </div>
        </div>

        <h2>NOTICE FOR LITTERING IN A PUBLIC PLACE</h2>
        <p>
          {vehicle
            ? <>To the registered owner of vehicle <b>{d.plate_display}</b>,</>
            : <>To the person shown in the photograph below,</>}
        </p>
        <p>
          The automated camera <b>{d.camera?.name || d.camera_id}</b> recorded littering in the designated clean zone
          <b> “{d.zone}”</b>. An officer has reviewed and verified the evidence. Littering in public places is
          prohibited under the Solid Waste Management Rules, 2016 and the bye-laws of this local body.
        </p>

        <table>
          <tbody>
            <tr><td>Date and time of offence</td><td>{fmtDateTime(d.occurred_at)}</td></tr>
            <tr><td>Place</td><td>{d.location || "—"} ({d.zone}), {d.ward || ""}</td></tr>
            <tr><td>Offender</td><td>{vehicle ? `${VEHICLE_LABEL[d.vehicle_category || "other"] || "Vehicle"} (${d.vehicle_class || "vehicle"})` : offenderLabel(d)}</td></tr>
            {vehicle && <tr><td>Registration number</td><td><b>{d.plate_display}</b></td></tr>}
            <tr><td>Case reference</td><td>#{d.id} · {d.uid}</td></tr>
            <tr><td>Penalty</td><td><b>{inr(d.fine_amount)}</b></td></tr>
            <tr><td>Pay by</td><td>{fmtDate(d.due_date)}</td></tr>
          </tbody>
        </table>

        <div className="photos">
          {d.evidence.scene && <img src={d.evidence.scene} alt="Scene at the time of the offence" />}
          <div style={{ display: "flex", flexDirection: "column", gap: 10 }}>
            {(d.evidence.person || d.evidence.vehicle) && <img src={d.evidence.person || d.evidence.vehicle} alt="Offender" />}
            {d.evidence.plate && <img src={d.evidence.plate} alt="Number plate" />}
          </div>
        </div>

        <p>
          You are required to pay the penalty by the date above at the ward office or through the payment channels
          of the local body, quoting the notice number. If the penalty is not paid on time, the matter may be
          escalated as per the applicable rules. You may raise an objection with the ward office within the same
          period; the video evidence will be kept until the case is closed.
        </p>

        <div className="sign">
          <div className="stamp">Office seal</div>
          <div style={{ textAlign: "right" }}>
            <div style={{ height: 40 }} />
            <div>Sanitary Inspector / Authorised Officer</div>
            <div style={{ color: "#555" }}>{settings?.department}</div>
          </div>
        </div>
        <p style={{ fontSize: 11, color: "#777", marginTop: 24 }}>
          Generated by Swachh Netra (college demonstration project). This is not an official document.
        </p>
      </article>
    </>
  );
}
